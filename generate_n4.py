# Создаем список с ID от 831 до 1441
START_ID = 831
words_data = [{"id": START_ID + idx, "reading": text} for idx, text in enumerate(raw_readings)]

def generate_voicevox_audio(word_id, text):
    file_path = os.path.join(OUTPUT_DIR, f"{word_id}.mp3")
    if os.path.exists(file_path):
        print(f"[{word_id}] Пропущен (уже существует)")
        return

    # Очистка текста от лишних символов
    clean_text = text.replace("〜", "").replace("—", "").replace("-", "").strip()
    if not clean_text:
        return

    try:
        # 1. Запрос параметров озвучки
        query_res = requests.post(
            f"{VOICEVOX_URL}/audio_query",
            params={"text": clean_text, "speaker": SPEAKER_ID},
            timeout=10
        )
        query_data = query_res.json()
        query_data["speedScale"] = 0.88  # Скорость речи (0.85 - 0.90 оптимально для обучения)

        # 2. Синтез звука
        synth_res = requests.post(
            f"{VOICEVOX_URL}/synthesis",
            params={"speaker": SPEAKER_ID},
            json=query_data,
            timeout=10
        )

        with open(file_path, "wb") as f:
            f.write(synth_res.content)

        print(f"✅ [{word_id}/{START_ID + len(raw_readings) - 1}] Готово: {clean_text}")
    except Exception as e:
        print(f"❌ Ошибка [{word_id}]: {e}")

print(f"🚀 Начинаем озвучку {len(words_data)} слов N4 (ID {START_ID} – {START_ID + len(words_data) - 1})...")
for item in words_data:
    generate_voicevox_audio(item["id"], item["reading"])
    time.sleep(0.03)

print(f"🎉 Все файлы успешно сгенерированы в папку '{OUTPUT_DIR}'!")